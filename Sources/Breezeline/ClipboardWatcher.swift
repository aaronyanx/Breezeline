import AppKit

@MainActor
final class ClipboardWatcher {
    static let sourceType = NSPasteboard.PasteboardType("com.aaronyanx.Breezeline.source")
    private static let ignoredTypes = [
        sourceType,
        NSPasteboard.PasteboardType("com.aaronyanx.Hangline.source"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard: NSPasteboard
    private let folder: URL
    private let onNew: (URL) -> Void
    private var lastChangeCount: Int
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general, folder: URL = Inbox.folder,
         onNew: @escaping (URL) -> Void) {
        self.pasteboard = pasteboard
        self.folder = folder
        self.onNew = onNew
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        // shortcut: polling can miss copies less than 0.5 seconds apart; use an explicit import action if needed.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkForImage() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func checkForImage() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard pasteboard.availableType(from: Self.ignoredTypes) == nil,
              let type = pasteboard.availableType(from: [.png, .tiff]),
              let data = pasteboard.data(forType: type),
              let bitmap = NSBitmapImageRep(data: data),
              let png = bitmap.representation(using: .png, properties: [:]),
              pasteboard.changeCount == changeCount else { return }

        let url = folder.appendingPathComponent("Clipboard-\(UUID().uuidString).png")
        do {
            try FileManager.default.createDirectory(
                at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try png.write(to: url, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            onNew(url)
        } catch {
            log.error("Could not import clipboard image: \(error.localizedDescription, privacy: .public)")
            NSSound.beep()
        }
    }
}
